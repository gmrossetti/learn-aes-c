#include <assert.h>
#include <stdio.h>
#include "aes.h"

static void test_encrypt_decrypt(void)
{
    // KEY: Thats my Kung Fu (16 ASCII characters, 1 byte each)
    const uint8_t key[] = {0x54, 0x68, 0x61, 0x74, 0x73, 0x20, 0x6D, 0x79, 0x20, 0x4B, 0x75, 0x6E, 0x67, 0x20, 0x46, 0x75};
    
    // MESSAGE: Two One Nine Two (16 ASCII characters, 1 byte each)
    const uint8_t msg[] = {0x54, 0x77, 0x6F, 0x20, 0x4F, 0x6E, 0x65, 0x20, 0x4E, 0x69, 0x6E, 0x65, 0x20, 0x54, 0x77, 0x6F};

    uint8_t c[16];
    encrypt(key, sizeof(key), msg, c);

    const uint8_t c_exp[] = {0x29, 0xC3, 0x50, 0x5F, 0x57, 0x14, 0x20, 0xF6, 0x40, 0x22, 0x99, 0xB3, 0x1A, 0x02, 0xD7, 0x3A};
    
    assert(memcmp(c, c_exp, 16) == 0);
}

int main(void)
{
    test_encrypt_decrypt();

    printf("All tests passed!\n");
    return 0;
}